"""Контекстные процессоры: общие данные для всех шаблонов сайта."""

from seminars_app.models import Seminar


def seminar_context(request):
    """Передать в каждый шаблон название сайта и число семинаров.

    request — текущий HTTP-запрос (здесь не используется, но Django
    всегда передаёт его контекстному процессору).
    Ключи возвращаемого словаря становятся переменными шаблона.
    """
    return {
        "site_name": "Система управления семинарами",
        # count() считает записи в базе, не загружая сами семинары.
        "seminars_total": Seminar.objects.count(),
    }
